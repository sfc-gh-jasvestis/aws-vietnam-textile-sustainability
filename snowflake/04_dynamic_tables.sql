-- On-demand snapshots. No automatic freshness claim.
USE DATABASE IDENTIFIER($DEMO_DB);
USE SCHEMA CURATED;
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT site.ID AS ENTITY_ID, site.NAME AS ENTITY_NAME,
       site.REGION, site.CATEGORY, site.STATUS,
       COUNT(*) AS EVENT_COUNT, SUM(o.EXCEEDANCE_COUNT) AS EXCEEDANCE_COUNT,
       SUM(o.OPERATING_HOURS) AS OPERATING_HOURS, SUM(o.PLANNED_HOURS) AS PLANNED_HOURS,
       SUM(o.DOWNTIME_HOURS) AS DOWNTIME_HOURS,
       SUM(o.INSPECTION_DUE) AS INSPECTION_DUE, SUM(o.INSPECTION_DONE) AS INSPECTION_DONE,
       SUM(o.THROUGHPUT_TONNES) AS THROUGHPUT_TONNES, SUM(o.CO2E_TONNES) AS CO2E_TONNES,
       SUM(o.SAMPLES_IN_LIMIT) AS SAMPLES_IN_LIMIT, SUM(o.WATER_SAMPLES) AS WATER_SAMPLES,
       SUM(o.GRIEVANCES) AS GRIEVANCES,
       100.0 * SUM(o.SAMPLES_IN_LIMIT) / NULLIF(SUM(o.WATER_SAMPLES), 0) AS IN_LIMIT_PCT,
       1000.0 * SUM(o.CO2E_TONNES) / NULLIF(SUM(o.THROUGHPUT_TONNES), 0) AS KG_CO2E_PER_T,
       100.0 * SUM(o.OPERATING_HOURS) / NULLIF(SUM(o.PLANNED_HOURS), 0) AS TREATMENT_UPTIME_PCT,
       100.0 * SUM(o.INSPECTION_DONE) / NULLIF(SUM(o.INSPECTION_DUE), 0) AS INSPECTION_COMPLETION_PCT,
       MAX(o.EVENT_DATE) AS SOURCE_WATERMARK
FROM RAW.MILL_DAILY o
JOIN RAW.MILLS site ON site.ID = o.ENTITY_ID
GROUP BY site.ID, site.NAME, site.REGION, site.CATEGORY, site.STATUS;

CREATE DYNAMIC TABLE CURATED.TREND_ANALYSIS
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT EVENT_DATE AS METRIC_DATE, COUNT(*) AS EVENT_COUNT,
       SUM(SAMPLES_IN_LIMIT) AS SAMPLES_IN_LIMIT, SUM(WATER_SAMPLES) AS WATER_SAMPLES,
       SUM(THROUGHPUT_TONNES) AS THROUGHPUT_TONNES, SUM(CO2E_TONNES) AS CO2E_TONNES,
       SUM(GRIEVANCES) AS GRIEVANCES, SUM(EXCEEDANCE_COUNT) AS EXCEEDANCE_COUNT,
       100.0 * SUM(SAMPLES_IN_LIMIT) / NULLIF(SUM(WATER_SAMPLES), 0) AS IN_LIMIT_PCT,
       1000.0 * SUM(CO2E_TONNES) / NULLIF(SUM(THROUGHPUT_TONNES), 0) AS KG_CO2E_PER_T
FROM RAW.MILL_DAILY
GROUP BY EVENT_DATE;

CREATE DYNAMIC TABLE CURATED.EXCEEDANCE_CAUSES
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT ROOT_CAUSE, SUM(EXCEEDANCE_COUNT) AS EXCEEDANCE_COUNT,
       SUM(DOWNTIME_HOURS) AS DOWNTIME_HOURS,
       SUM(WATER_SAMPLES) - SUM(SAMPLES_IN_LIMIT) AS SAMPLES_OVER_LIMIT
FROM RAW.MILL_DAILY
WHERE EXCEEDANCE_COUNT > 0
GROUP BY ROOT_CAUSE;

CREATE DYNAMIC TABLE CURATED.KPI_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
WITH observations AS (
  SELECT SUM(SAMPLES_IN_LIMIT) AS SAMPLES_IN_LIMIT, SUM(WATER_SAMPLES) AS WATER_SAMPLES,
         SUM(THROUGHPUT_TONNES) AS THROUGHPUT_TONNES, SUM(CO2E_TONNES) AS CO2E_TONNES,
         SUM(GRIEVANCES) AS GRIEVANCES, SUM(EXCEEDANCE_COUNT) AS EXCEEDANCES,
         SUM(OPERATING_HOURS) AS OPERATING_HOURS, SUM(PLANNED_HOURS) AS PLANNED_HOURS,
         MAX(EVENT_DATE) AS SOURCE_WATERMARK
  FROM RAW.MILL_DAILY
), sites AS (SELECT COUNT(*) AS SITE_COUNT FROM RAW.MILLS),
leaks AS (
  SELECT 100.0 * SUM(LEAST(LEAKS_CLOSED, LEAKS_DETECTED)) / NULLIF(SUM(LEAKS_DETECTED), 0) AS LEAK_CLOSURE_PCT
  FROM RAW.STEAM_TRAP_SURVEY
), metrics AS (
  SELECT 1 AS SORT_ORDER, 'Effluent Within Threshold' AS TITLE,
         100.0 * SAMPLES_IN_LIMIT / NULLIF(WATER_SAMPLES, 0) AS VALUE_NUM, '%' AS UNIT FROM observations
  UNION ALL SELECT 2, 'Environmental Exceedances', EXCEEDANCES, '' FROM observations
  UNION ALL SELECT 3, 'Emissions Intensity', 1000.0 * CO2E_TONNES / NULLIF(THROUGHPUT_TONNES, 0), ' kg CO2e/t' FROM observations
  UNION ALL SELECT 4, 'Total Emissions (t CO2e)', CO2E_TONNES, '' FROM observations
  UNION ALL SELECT 5, 'Effluent Treatment Uptime', 100.0 * OPERATING_HOURS / NULLIF(PLANNED_HOURS, 0), '%' FROM observations
  UNION ALL SELECT 6, 'Mills Monitored', SITE_COUNT, '' FROM sites
  UNION ALL SELECT 7, 'Steam Trap Leaks Closed', LEAK_CLOSURE_PCT, '%' FROM leaks
  UNION ALL SELECT 8, 'Community Grievances', GRIEVANCES, '' FROM observations
)
SELECT metrics.SORT_ORDER, metrics.TITLE, metrics.VALUE_NUM,
       IFF(metrics.VALUE_NUM IS NULL, 'Unavailable',
           CASE WHEN metrics.UNIT = '' THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM), '999,999,999,990'))
                ELSE TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 1), '999,990.0')) END || metrics.UNIT) AS DISPLAY,
       'neutral' AS STATUS, observations.SOURCE_WATERMARK
FROM metrics CROSS JOIN observations;

ALTER DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.TREND_ANALYSIS SUSPEND;
ALTER DYNAMIC TABLE CURATED.EXCEEDANCE_CAUSES SUSPEND;
ALTER DYNAMIC TABLE CURATED.KPI_SUMMARY SUSPEND;
