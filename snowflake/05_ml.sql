-- Exceedance-risk scoring and emissions forecast over the synthetic snapshot.
-- Predicts P(environmental exceedance in the next 7 days) per mill and reports
-- out-of-time holdout metrics; nothing is seeded as a prediction.
USE DATABASE IDENTIFIER($DEMO_DB);
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE VIEW ML.EXCEEDANCE_FEATURES AS
SELECT r.ENTITY_ID, r.EVENT_DATE, t.CATEGORY, t.AGE_YEARS,
       r.COD_MGL, r.ETP_LOAD_PCT,
       AVG(r.COD_MGL) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 6 PRECEDING AND CURRENT ROW) AS COD_7D,
       SUM(r.EXCEEDANCE_COUNT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 29 PRECEDING AND CURRENT ROW) AS EXCEEDANCES_30D,
       IFF(SUM(r.EXCEEDANCE_COUNT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 1 FOLLOWING AND 7 FOLLOWING) > 0,
           'EXCEEDANCE', 'OK') AS LABEL,
       COUNT(*) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 1 FOLLOWING AND 7 FOLLOWING) AS FUTURE_DAYS
FROM RAW.MILL_DAILY r JOIN RAW.MILLS t ON t.ID = r.ENTITY_ID
-- Regional storm events are not mill-driven, so they are excluded from training.
WHERE r.ROOT_CAUSE NOT IN ('Monsoon stormwater surge', 'Typhoon flood inflow') OR r.EXCEEDANCE_COUNT = 0;

-- Time-based split: train on older labelled days, hold out the most recent 14 labelled days.
CREATE VIEW ML.EXCEEDANCE_TRAIN AS
SELECT CATEGORY, AGE_YEARS, COD_MGL, ETP_LOAD_PCT, COD_7D, EXCEEDANCES_30D, LABEL
FROM ML.EXCEEDANCE_FEATURES
WHERE FUTURE_DAYS = 7 AND EVENT_DATE < DATEADD('day', -21, CURRENT_DATE());

CREATE VIEW ML.EXCEEDANCE_HOLDOUT AS
SELECT ENTITY_ID, EVENT_DATE, CATEGORY, AGE_YEARS, COD_MGL, ETP_LOAD_PCT, COD_7D, EXCEEDANCES_30D, LABEL
FROM ML.EXCEEDANCE_FEATURES
WHERE FUTURE_DAYS = 7 AND EVENT_DATE >= DATEADD('day', -21, CURRENT_DATE());

CREATE SNOWFLAKE.ML.CLASSIFICATION ML.EXCEEDANCE_RISK_MODEL(
  INPUT_DATA => TABLE(ML.EXCEEDANCE_TRAIN),
  TARGET_COLNAME => 'LABEL'
);

-- Out-of-time holdout: precision/recall at 0.5 versus the base rate.
CREATE TABLE ML.EXCEEDANCE_RISK_HOLDOUT_METRICS AS
WITH scored AS (
  SELECT LABEL, ML.EXCEEDANCE_RISK_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
           'CATEGORY', CATEGORY, 'AGE_YEARS', AGE_YEARS, 'COD_MGL', COD_MGL,
           'ETP_LOAD_PCT', ETP_LOAD_PCT, 'COD_7D', COD_7D, 'EXCEEDANCES_30D', EXCEEDANCES_30D)):probability:EXCEEDANCE::FLOAT AS P
  FROM ML.EXCEEDANCE_HOLDOUT
)
SELECT COUNT(*) AS N,
       AVG(IFF(LABEL = 'EXCEEDANCE', 1, 0)) AS BASE_RATE,
       SUM(IFF(P >= 0.5 AND LABEL = 'EXCEEDANCE', 1, 0)) / NULLIF(SUM(IFF(P >= 0.5, 1, 0)), 0) AS PRECISION_AT_50,
       SUM(IFF(P >= 0.5 AND LABEL = 'EXCEEDANCE', 1, 0)) / NULLIF(SUM(IFF(LABEL = 'EXCEEDANCE', 1, 0)), 0) AS RECALL_AT_50,
       CURRENT_TIMESTAMP() AS EVALUATED_AT
FROM scored;

-- Latest-day score per mill (label unknown, so excluded from features).
CREATE TABLE ML.EXCEEDANCE_RISK_SCORES AS
WITH latest AS (
  SELECT * FROM ML.EXCEEDANCE_FEATURES
  QUALIFY ROW_NUMBER() OVER (PARTITION BY ENTITY_ID ORDER BY EVENT_DATE DESC) = 1
), scored AS (
  SELECT ENTITY_ID, EVENT_DATE,
         ML.EXCEEDANCE_RISK_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
           'CATEGORY', CATEGORY, 'AGE_YEARS', AGE_YEARS, 'COD_MGL', COD_MGL,
           'ETP_LOAD_PCT', ETP_LOAD_PCT, 'COD_7D', COD_7D, 'EXCEEDANCES_30D', EXCEEDANCES_30D)) AS P
  FROM latest
)
SELECT ENTITY_ID, EVENT_DATE AS SCORED_AS_OF,
       ROUND(P:probability:EXCEEDANCE::FLOAT, 4) AS EXCEEDANCE_PROB_7D,
       CASE WHEN P:probability:EXCEEDANCE::FLOAT >= 0.5 THEN 'High'
            WHEN P:probability:EXCEEDANCE::FLOAT >= 0.25 THEN 'Medium' ELSE 'Low' END AS RISK_BAND,
       CURRENT_TIMESTAMP() AS SCORED_AT
FROM scored;

-- Group-wide daily emissions forecast (14 days, t CO2e) from the daily series.
CREATE VIEW ML.DAILY_EMISSIONS AS
SELECT EVENT_DATE::TIMESTAMP_NTZ AS TS, SUM(CO2E_TONNES)::FLOAT AS CO2E_TONNES
FROM RAW.MILL_DAILY GROUP BY EVENT_DATE;

CREATE SNOWFLAKE.ML.FORECAST ML.EMISSIONS_FORECAST_MODEL(
  INPUT_DATA => TABLE(ML.DAILY_EMISSIONS),
  TIMESTAMP_COLNAME => 'TS',
  TARGET_COLNAME => 'CO2E_TONNES'
);

CREATE TABLE ML.EMISSIONS_FORECAST AS
SELECT TS::DATE AS FORECAST_DATE, ROUND(FORECAST) AS CO2E_TONNES,
       ROUND(GREATEST(0, LOWER_BOUND)) AS LOWER_BOUND, ROUND(UPPER_BOUND) AS UPPER_BOUND
FROM TABLE(ML.EMISSIONS_FORECAST_MODEL!FORECAST(FORECASTING_PERIODS => 14));
